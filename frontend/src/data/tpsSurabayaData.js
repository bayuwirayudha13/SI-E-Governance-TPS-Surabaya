// Mappings & Helper functions
export const KECAMATAN_SURABAYA_LIST = Array.from(new Set(TPS_SURABAYA_ALL.map((t) => t.kecamatan))).sort();

export function getTpsByKelurahan(kelurahanName) {
  if (!kelurahanName) return [];
  const clean = kelurahanName.trim().toLowerCase();
  
  // Exact match on kelurahanList
  const matched = TPS_SURABAYA_ALL.filter((tps) =>
    tps.kelurahanList.some((k) => k.toLowerCase() === clean || clean.includes(k.toLowerCase()) || k.toLowerCase().includes(clean))
  );

  if (matched.length > 0) return matched;

  // Fallback: search by kecamatan or substring
  return TPS_SURABAYA_ALL.filter(
    (tps) =>
      tps.nama.toLowerCase().includes(clean) ||
      tps.lokasi.toLowerCase().includes(clean) ||
      tps.kecamatan.toLowerCase().includes(clean)
  );
}

export function getTpsByKecamatan(kecamatanName) {
  if (!kecamatanName) return [];
  const clean = kecamatanName.trim().toLowerCase();
  return TPS_SURABAYA_ALL.filter((tps) => tps.kecamatan.toLowerCase() === clean);
}
